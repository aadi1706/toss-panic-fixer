// Builds the featured real-match replays from a local copy of Cricsheet's IPL archive.
//   1. curl -L -o .cache/cricsheet-ipl/ipl_json.zip https://cricsheet.org/downloads/ipl_json.zip
//   2. unzip -q .cache/cricsheet-ipl/ipl_json.zip -d .cache/cricsheet-ipl/json
//   3. node scripts/build-replay.mjs
// Writes data/replay/<id>.json and the generated src/replay-registry.js. Data: Cricsheet.org (ODC-By).
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { buildIndex, buildReplay } from '../src/replay.js';

const dir = new URL('../.cache/cricsheet-ipl/json/', import.meta.url);
const FEATURED = ['1312200', '1254117', '1181768', '981019']; // IPL finals 2022, 2021, 2019, 2016 (clean 11-a-side seasons)

const raw = readdirSync(dir).filter((f) => f.endsWith('.json')).map((f) => ({ id: f.replace('.json', ''), ...JSON.parse(readFileSync(new URL(f, dir), 'utf8')) }));
const index = buildIndex(raw);
mkdirSync(new URL('../data/replay/', import.meta.url), { recursive: true });

const ids = [];
for (const id of FEATURED) {
  const { meta, match } = buildReplay(index, id);
  writeFileSync(new URL(`../data/replay/${id}.json`, import.meta.url), JSON.stringify({ meta, match }));
  ids.push(id);
  console.log(`${id}  ${meta.source.label}  (${Object.values(meta.squads).flat().length} players, ${meta.source.diagnostics.benched} benched)`);
}
const lines = [
  '// GENERATED by scripts/build-replay.mjs. Do not edit by hand.',
  ...ids.map((id) => `import r${id} from '../data/replay/${id}.json' with { type: 'json' };`),
  `export const REPLAYS = [${ids.map((id) => `r${id}`).join(', ')}];`,
  '',
];
writeFileSync(new URL('../src/replay-registry.js', import.meta.url), lines.join('\n'));
console.log('wrote src/replay-registry.js');
